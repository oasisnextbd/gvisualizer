// Builds search-index.js for the home-page search across both courses.
// Run after editing any data file:  node tools/build-search-index.js
const fs = require('fs'), path = require('path'), vm = require('vm');
const ROOT = path.join(__dirname, '..');
const COURSES = [
  { dir: 'mass-transfer', code: 'ChE 303', config: 'mass-transfer/course.js' },
  { dir: 'question-bank', code: 'CHE 301', config: null },
  { dir: 'unit-ops', code: 'CHE 311', config: 'unit-ops/course.js' },
];
const strip = s => String(s || '')
  .replace(/!\[[^\]]*\]\([^)]*\)/g, ' ')            // images
  .replace(/\$\$[\s\S]*?\$\$/g, ' ')                 // display math
  .replace(/\\\[[\s\S]*?\\\]/g, ' ')
  .replace(/\$([^$]*)\$/g, (m, x) => x.replace(/\\[a-zA-Z]+/g, ' ').replace(/[{}_^\\]/g, ''))
  .replace(/\\\(([\s\S]*?)\\\)/g, (m, x) => x.replace(/\\[a-zA-Z]+/g, ' ').replace(/[{}_^\\]/g, ''))
  .replace(/^\|.*\|$/gm, ' ')                        // tables
  .replace(/[*#>`|]/g, '').replace(/\s+/g, ' ').trim();
const out = [], topics = [];
const topicIdx = n => { let i = topics.indexOf(n); if (i < 0) { i = topics.length; topics.push(n); } return i; };
for (const c of COURSES) {
  const win = {};
  const ctx = vm.createContext({ window: win, console, localStorage: { getItem: () => null, setItem() {} },
    document: { createElement: () => ({}), head: { appendChild() {} }, querySelectorAll: () => [] }, location: { pathname: '/' } });
  if (c.config) vm.runInContext(fs.readFileSync(path.join(ROOT, c.config), 'utf8'), ctx);
  vm.runInContext(fs.readFileSync(path.join(ROOT, 'question-bank/qb.js'), 'utf8'), ctx);
  const QB = win.QB; ctx.QB = QB;
  for (const f of fs.readdirSync(path.join(ROOT, c.dir, 'data')).filter(f => f.endsWith('.js')).sort())
    vm.runInContext(fs.readFileSync(path.join(ROOT, c.dir, 'data', f), 'utf8'), ctx);
  for (const p of QB.parts) {
    const t = QB.topic(p.topic);
    out.push([c.dir, p.id, QB.label(p), strip(p.sub), strip((p.stem ? p.stem + ' ' : '') + p.text).slice(0, 260), topicIdx(c.code + ' · ' + (t ? t.name : '')), p.type || '', p.practice ? 1 : 0, p.key]);
  }
}
const js = '/* generated by tools/build-search-index.js: [course dir, id, label, title, question text, topic index, type, practice, paper] */\nwindow.GV_TOPICS=' + JSON.stringify(topics) + ';\nwindow.GV_INDEX=' + JSON.stringify(out) + ';\n';
fs.writeFileSync(path.join(ROOT, 'search-index.js'), js);
console.log('search-index.js:', out.length, 'questions,', Math.round(js.length / 1024), 'KB');
